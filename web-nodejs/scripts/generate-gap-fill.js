function flatten(obj, prefix = '') {
    const result = {};
    for (const [k, v] of Object.entries(obj)) {
        const key = prefix ? `${prefix}.${k}` : k;
        if (v && typeof v === 'object' && !Array.isArray(v)) Object.assign(result, flatten(v, key));
        else result[key] = String(v ?? '');
    }
    return result;
}

function unflatten(flat) {
    const root = {};
    for (const [key, value] of Object.entries(flat)) {
        const parts = key.split('.');
        let cur = root;
        for (let i = 0; i < parts.length - 1; i++) {
            const p = parts[i];
            if (!cur[p] || typeof cur[p] !== 'object') cur[p] = {};
            cur = cur[p];
        }
        cur[parts[parts.length - 1]] = value;
    }
    return root;
}

function pickPatch(patch, keys) {
    const flat = flatten(patch);
    const out = {};
    for (const k of keys) {
        if (flat[k] !== undefined) out[k] = flat[k];
    }
    return out;
}

function transformStrings(flat, rules) {
    const out = { ...flat };
    for (const [key, value] of Object.entries(out)) {
        let v = value;
        for (const [from, to] of rules) {
            v = v.split(from).join(to);
        }
        out[key] = v;
    }
    return out;
}


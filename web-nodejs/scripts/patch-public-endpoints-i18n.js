for (const file of locales) {
    const locale = file.replace('.json', '');
    const filePath = path.join(langDir, file);
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

    if (locale !== 'en') {
        const dashPatch = dashboardPatches[locale];
        if (dashPatch && data.dashboard) {
            Object.assign(data.dashboard, dashPatch);
        }
        const settingsPatch = settingsPatches[locale];
        if (settingsPatch && data.settings) {
            Object.assign(data.settings, settingsPatch);
        }
    }

    fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
    console.log('patched', file);
}
